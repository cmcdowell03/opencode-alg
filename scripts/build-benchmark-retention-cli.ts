import { createHash } from "node:crypto"
import { closeSync, fstatSync, openSync, readSync, writeFileSync } from "node:fs"
import { resolve } from "node:path"
import { z } from "zod"
import { measureBuildBenchmarkRetention } from "./build-benchmark-retention.ts"

const MAX_INPUT_BYTES = 16 * 1024 * 1024
const MAX_REPORT_BYTES = 32 * 1024 * 1024
const InputSchema = z.object({
  schema: z.literal("alg-retention-input-v1"),
  events: z.array(z.unknown()).max(20_000),
  expectedFacts: z.array(z.unknown()).max(5_000),
  boundaries: z.unknown().optional(),
}).strict()

function readInput(path: string): Buffer {
  const handle = openSync(path, "r")
  try {
    const before = fstatSync(handle)
    if (!before.isFile() || before.size > MAX_INPUT_BYTES) throw new Error("retention_input_not_regular_or_oversized")
    const buffer = Buffer.alloc(before.size + 1)
    let length = 0
    while (length < buffer.length) {
      const count = readSync(handle, buffer, length, buffer.length - length, null)
      if (!count) break
      length += count
    }
    const after = fstatSync(handle)
    if (length !== before.size || after.size !== before.size || after.mtimeMs !== before.mtimeMs || after.ctimeMs !== before.ctimeMs)
      throw new Error("retention_input_changed_during_read")
    return buffer.subarray(0, length)
  } finally { closeSync(handle) }
}

/** Offline only: observations are supplied by a trusted collector, never generated by the model being evaluated. */
export function analyzeRetentionFile(inputPath: string, outputPath: string) {
  if (resolve(inputPath) === resolve(outputPath)) throw new Error("retention_output_must_be_new")
  const bytes = readInput(inputPath)
  let parsed: z.infer<typeof InputSchema>
  try { parsed = InputSchema.parse(JSON.parse(new TextDecoder("utf-8", { fatal: true }).decode(bytes))) }
  catch { throw new Error("retention_input_invalid") }
  const measurement = measureBuildBenchmarkRetention(parsed.events, parsed.expectedFacts, parsed.boundaries)
  if (measurement.boundaryRetention.status === "invalid_input" ||
    ("issues" in measurement.boundaryRetention && measurement.boundaryRetention.issues.length > 0))
    throw new Error("retention_boundary_evidence_invalid")
  const report = {
    inputSha256: createHash("sha256").update(bytes).digest("hex"),
    ...measurement,
    provenance: "caller_supplied_observations_not_independently_authenticated_by_this_cli",
  }
  const output = Buffer.from(`${JSON.stringify(report, null, 2)}\n`)
  if (output.byteLength > MAX_REPORT_BYTES) throw new Error("retention_report_oversized")
  writeFileSync(outputPath, output, { flag: "wx", mode: 0o600 })
  return { outputPath: resolve(outputPath), inputSha256: report.inputSha256,
    outputSha256: createHash("sha256").update(output).digest("hex"),
    taskCount: report.tasks.length, eventCount: report.eventCount }
}

if (import.meta.main) {
  const args = process.argv.slice(2)
  if (args.length !== 2) throw new Error("Usage: bun scripts/build-benchmark-retention-cli.ts <observations.json> <new-report.json>")
  console.log(JSON.stringify(analyzeRetentionFile(args[0]!, args[1]!)))
}
